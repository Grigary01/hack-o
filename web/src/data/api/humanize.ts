/**
 * Тексты расчётов сохраняются в данных при сборке (app/geo/*) и пишутся для инженеров:
 * «по OSM», «азимут 305°», «ось ВПП 06/24 (посадочный курс 64°)». Перед показом гостю
 * переводим их на обычный язык. Смысл и числа, важные гостю, не меняются.
 */
const RULES: [RegExp, string][] = [
  [/\s*\(по OSM\)/g, ''],
  [/\s*\(азимут \d+°\)/g, ''],
  [/\s*\(посадочный курс \d+°\)/g, ''],
  [/по оси ВПП [\d/]+/g, 'вдоль взлётной полосы'],
  [/ВПП [\d/]+/g, 'взлётной полосы'],
  // \b в JS не видит кириллицу как буквы — граница слова через пробел/начало строки.
  [/(^|\s)(?:по|в) OSM\b/g, '$1на карте'],
  [/Пляж OSM/g, 'Пляж'],
  [/\bOSM\b/g, 'OpenStreetMap'],
  // Признак «деревья и дома перед окнами» мог быть сохранён со старыми формулировками.
  [/по базовому расчёту/g, 'по основному расчёту'],
  [/во всех сценариях высоты деревьев и домов/g, 'при любой высоте деревьев и домов'],
  [/ни в одном сценарии/g, 'при любой высоте деревьев'],
  // Формулировки разбора запроса (app/ml/rules_parser.py): по смыслу — «не реализовано».
  [/Пока не поддерживается: ([^;.]+)/g, '$1 — не реализовано в текущей версии'],
  [/Поддерживается только прибрежный Адлер/g, 'В текущей версии доступен только Адлер'],
  [/Не нашёл поддерживаемых пожеланий/g, 'В запросе не нашлось пожеланий, которые мы умеем проверять'],
  [/Сейчас система проверяет:/g, 'Сейчас мы проверяем:'],
];

export function humanize(text: string): string;
export function humanize(text: string | null | undefined): string | null | undefined;
export function humanize(text: string | null | undefined) {
  if (!text) return text;
  return RULES.reduce((acc, [pattern, replacement]) => acc.replace(pattern, replacement), text);
}

/** Название расчёта для подписи источника: «OSM здания и coastline + Copernicus DEM GLO-30» → по-человечески. */
export function modelSourceName(name: string | null | undefined): string {
  const raw = name ?? '';
  if (/ВПП|аэропорт/i.test(raw)) return 'Расчёт по схеме полётов аэропорта Сочи и рельефу';
  if (/деревьев|сценари/i.test(raw)) return 'Расчёт вида с учётом деревьев и домов';
  if (/здани/i.test(raw)) return 'Расчёт по карте зданий, берега и рельефа';
  if (/пешеход/i.test(raw)) return 'Расчёт по пешеходным маршрутам и рельефу';
  if (/дорог/i.test(raw)) return 'Расчёт по карте дорог и заведений';
  return 'Расчёт по открытым данным';
}
